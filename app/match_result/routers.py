from fastapi import APIRouter, Depends, status, Query
from app.db.config import SessionDep, get_session
from app.match_result.schemas import MatchResultCreate, MatchResultOut
from app.media.schemas import MediaOut # Ensure this schema exists for response modeling
from app.match_result.services import create_match_entry, get_matches_by_face, search_media_by_text
from typing import List

router = APIRouter()

@router.post("/", response_model=MatchResultOut, status_code=status.HTTP_201_CREATED)
async def add_new_match_result(data: MatchResultCreate, session: SessionDep):
    """Saves a verification match relationship payload generated by face analysis engines"""
    return await create_match_entry(session, data)

@router.get("/face/{face_id}", response_model=List[MatchResultOut])
async def read_gallery_matches_for_user_face(face_id: str, session: SessionDep):
    """Allows pulling specific media matched lists mapped for a single user face"""
    return await get_matches_by_face(session, face_id)

@router.get("/search/text", response_model=List[MediaOut])
async def search_event_media(
    event_id: str, 
    query: str = Query(..., description="The description to search for (e.g., 'red hair')"), 
    session: SessionDep = None
    ):
    """
    Performs natural language search on event media using CLIP embeddings.
    """
    return await search_media_by_text(session, event_id, query)